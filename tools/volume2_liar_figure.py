#!/usr/bin/env python3
"""Regenerate the complete finite Euler/strong-liar plot for Volume 2.

Counts use prime-power cyclic coordinates for Euler liars and Monier's
formula for strong liars. Tests independently enumerate every unit base.
"""

import argparse
import math
from pathlib import Path


def factors(n):
    result = {}
    p = 2
    while p*p <= n:
        while n % p == 0:
            result[p] = result.get(p, 0)+1
            n //= p
        p += 1
    if n > 1:
        result[n] = result.get(n, 0)+1
    return result


def liar_counts(n):
    fs = factors(n)
    sizes = [(p-1)*p**(e-1) for p, e in fs.items()]
    phi = math.prod(sizes)
    # The Jacobi sign of a tuple of primitive-root exponents t_i is
    # (-1)^(sum e_i*t_i). Count each possible global sign separately.
    euler = 0
    for sign in (0, 1):
        parity_counts = [1, 0]
        for size, e in zip(sizes, fs.values()):
            local = [0, 0]
            for t in range(size):
                if ((n-1)//2*t-sign*(size//2)) % size == 0:
                    local[e*t % 2] += 1
            a, b = parity_counts
            parity_counts = [a*local[0]+b*local[1], a*local[1]+b*local[0]]
        euler += parity_counts[sign]
    d = n-1
    while d % 2 == 0:
        d //= 2
    nus, odd_parts = [], []
    for p in fs:
        m, nu = p-1, 0
        while m % 2 == 0:
            m //= 2
            nu += 1
        nus.append(nu)
        odd_parts.append(m)
    r, nu = len(fs), min(nus)
    strong = math.prod(math.gcd(d, m) for m in odd_parts)*(1+(2**(r*nu)-1)//(2**r-1))
    return phi, euler, strong


def render():
    lines = [r'% Complete data, regenerated by python3 tools/volume2_liar_figure.py.',
             r'% Euler: hollow coral circles. Strong: filled charcoal dots. No cutoff.',
             r'\begin{tikzpicture}[x=0.0062cm,y=8cm]',
             r'\draw[->] (0,0) -- (1560,0) node[right] {\scriptsize $n$};',
             r'\draw[->] (0,0) -- (0,0.56);',
             r'\draw[gray!40,dashed] (0,0.25) -- (1500,0.25); \node[left] at (0,0.25) {\scriptsize $\frac14$};',
             r'\draw[gray!40,dashed] (0,0.50) -- (1500,0.50); \node[left] at (0,0.50) {\scriptsize $\frac12$};']
    for x in (500, 1000, 1500):
        lines.append(r'\node[below] at ('+str(x)+r',0) {\scriptsize $'+str(x)+r'$};')
    for n in range(9, 1500, 2):
        fs = factors(n)
        if len(fs) == 1 and next(iter(fs.values())) == 1:
            continue
        phi, euler, strong = liar_counts(n)
        lines.append(r'\draw[Goldenrod!85!black,line width=0.35pt] ('+f'{n},{euler/phi:.6f}'+r') circle (1.1pt);')
        lines.append(r'\fill[MidnightBlue] ('+f'{n},{strong/phi:.6f}'+r') circle (0.6pt);')
    lines.append(r'\end{tikzpicture}')
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1]/'volume2-integers/figures/ch03-liars.tex'
    expected = render()
    if args.check:
        if target.read_text() != expected:
            raise SystemExit('Liar figure is stale; run python3 tools/volume2_liar_figure.py')
    else:
        target.write_text(expected)


if __name__ == '__main__':
    main()
