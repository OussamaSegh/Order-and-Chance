"""One locked cover master: positions and type settings measured from Volume 0."""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / 'tools/assets/series-template.json'


def settings():
    return json.loads(CONFIG.read_text())


def tex_source():
    data=settings()
    macros={
        'COVERLEFT':'text_left_in', 'COVERNUMTOP':'number_top_ratio',
        'COVERNUMSIZE':'number_size_pt', 'COVERNUMTRACK':'number_tracking',
        'COVERTITLETOP':'title_top_ratio','COVERTITLESIZE':'title_size_pt',
        'COVERTITLELEADING':'title_leading_pt','COVERTITLESTRETCH':'title_stretch',
        'COVERTITLEWIDTH':'title_width_in','COVERSUBTOP':'subtitle_top_ratio',
        'COVERSUBSIZE':'subtitle_size_pt','COVERSUBTRACK':'subtitle_tracking',
        'COVERSUBSTRETCH':'subtitle_stretch',
        'COVERBACKSIZE':'back_body_size_pt','COVERBACKLEADING':'back_body_leading_pt',
        'COVERBACKMAXHEIGHT':'back_body_max_height_ratio'}
    text='% Generated by tools/series_cover.py from the single series master.\n'+''.join(
        '\\def\\'+macro+'{'+str(data[key])+'}\n' for macro,key in macros.items())
    for prefix,key in [('NUM','number'),('TITLE','title'),('SUB','subtitle')]:
        value=1-data[key+'_baseline_source_px']/1500
        text+='\\def\\COVER'+prefix+'BASE{'+str(value)+'}\n'
    for number,lines in check_titles().items():
        baseline=subtitle_baseline(number, len(lines))
        text+='\\expandafter\\def\\csname ocSubBase@'+number+'\\endcsname{'+str(1-baseline/1500)+'}\n'
    text+='\\def\\coversubtitlebase#1{\\csname ocSubBase@#1\\endcsname}\n'
    return text


def subtitle_baseline(number, line_count=None):
    """Keep the reference gap below the last title line, including one-line titles."""
    data=settings()
    if line_count is None:line_count=len(check_titles()[str(number)])
    leading_px=data['title_leading_pt']*175/72.27
    return data['subtitle_baseline_source_px']-(2-line_count)*leading_px


def subtitle_cap_top(number):
    return subtitle_baseline(number)-(settings()['subtitle_baseline_source_px']-600)


def check_sync():
    path=ROOT/'tools/cover-template.tex'
    if not path.exists() or path.read_text()!=tex_source():
        raise ValueError('Cover master TeX is stale; run tools/series_cover.py')


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def books():
    result=[]
    for main in sorted(ROOT.glob('tome*/main.tex')):
        heading=re.search(r'^% epub-title: (.+)$',main.read_text(),re.M)[1]
        number=re.search(r'Volume ([A-Z0-9]+):',heading)[1]
        result.append((number,heading.split(': ',1)[1],main.parent.name))
    return result


def check_titles():
    from PIL import ImageFont
    data=settings();pixels_per_pt=175/72.27
    font=ImageFont.truetype(str(ROOT/data['title_font']),data['title_size_pt']*pixels_per_pt)
    maximum=data['title_width_in']*175
    wrapped={}
    for number,title,_ in books():
        lines=['']
        for word in title.split():
            trial=(lines[-1]+' '+word).strip()
            if font.getlength(trial)*data['title_stretch'] > maximum:
                lines.append(word)
            else:lines[-1]=trial
        if len(lines)>2 or any(font.getlength(line)*data['title_stretch']>maximum for line in lines):
            raise ValueError(f'Volume {number}: title needs editing to fit the fixed two-line master')
        wrapped[number]=lines
    return wrapped


if __name__=='__main__':
    import sys
    if '--check' in sys.argv:check_sync();check_titles()
    else:(ROOT/'tools/cover-template.tex').write_text(tex_source())
