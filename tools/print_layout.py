"""Canonical paperback geometry; generated TeX and actual-page-count specifications."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAYOUT = json.loads((ROOT / 'common/print-layout.json').read_text())

def tex():
    names = {'trim_width_in': 'PRINTWIDTH', 'trim_height_in': 'PRINTHEIGHT',
             'bleed_in': 'PRINTBLEED', 'spine_in_per_page': 'PRINTSPINECOEFF'}
    return '% Generated by tools/print_layout.py; edit print-layout.json.\n' + ''.join(
        rf'\newcommand{{\{name}}}{{{LAYOUT[key]}}}' + '\n' for key, name in names.items())

def check_sync():
    if (ROOT / 'common/print-layout.tex').read_text() != tex():
        raise ValueError('Run python3 tools/print_layout.py to sync paperback geometry')

def specification(pages, inner='0.75in'):
    pages = int(pages)
    if not 24 <= pages <= 828:
        raise ValueError(f'{pages} pages: outside paperback limits (24–828)')
    kdp_pages = (pages + 1) // 2 * 2
    spine = round(kdp_pages * LAYOUT['spine_in_per_page'], 4)
    return dict(LAYOUT, interior_pages=pages, kdp_pages=kdp_pages, inner_margin=inner,
                spine_in=spine, wrap_width_in=2*LAYOUT['trim_width_in']+2*LAYOUT['bleed_in']+spine,
                wrap_height_in=LAYOUT['trim_height_in']+2*LAYOUT['bleed_in'],
                interior_bleed=False)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--pages', type=int)
    parser.add_argument('--inner', default='0.75in')
    args = parser.parse_args()
    if args.pages is not None:
        check_sync()
        print(json.dumps(specification(args.pages, args.inner), indent=2))
    elif args.check:
        check_sync()
    else:
        (ROOT / 'common/print-layout.tex').write_text(tex())
