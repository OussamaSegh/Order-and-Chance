"""Approved front: shared Cormorant/Fira lockup, per-volume art, baked optical shifts."""
import json
import re
from pathlib import Path

import arts
import collatz_art

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PPI = 1121 / 6.0
MAXW = 4.6
SMALL = {'and', 'of', 'the', 'from', 'to', 'a', 'meets'}
# Widths of the 42pt Regular titles, in inches, used only to choose a line break.
TITLE_WIDTH = {
    '1': 3.46, '2': 2.79, '3': 2.32, '4': 1.71, '5': 2.64, '6': 2.49, '7': 1.49,
    '8': 1.91, '9': 1.55, '10': 2.72, '11': 2.88, '12': 3.79, '13': 2.54, '14': 2.53,
    '15': 4.21,
}


def load_offsets():
    return json.loads((HERE / 'centring.json').read_text())['volumes']


def trk(text, ls):
    return r'{\addfontfeatures{LetterSpace=%s}%s\kern-%.4fem}' % (ls, text, ls / 100)


def point(x, y):
    return '(%.4fin,%.4fin)' % (x, y)


def rule(y, w=1.3):
    g, d = 0.085, 0.034
    cx = 3.0
    return [
        r'\draw[ocCoral,line width=0.55pt] %s--%s;' % (point(cx - w / 2, y), point(cx - g, y)),
        r'\draw[ocCoral,line width=0.55pt] %s--%s;' % (point(cx + g, y), point(cx + w / 2, y)),
        r'\fill[ocCoral] %s--%s--%s--%s--cycle;' % (
            point(cx, y + d), point(cx + d, y), point(cx, y - d), point(cx - d, y)),
    ]


def title_lines(number, title):
    if TITLE_WIDTH[str(number)] <= MAXW:
        return [title]
    words = title.split()
    ok = [i for i in range(1, len(words)) if words[i - 1].lower() not in SMALL]
    best = min(ok, key=lambda i: abs(len(' '.join(words[:i])) - len(' '.join(words[i:]))))
    return [' '.join(words[:best]), ' '.join(words[best:])]


def subtitle_lines(number):
    text = (ROOT / 'common/volume-subtitles.tex').read_text()
    body = re.search(r'occoversubtitle@%s\\endcsname\{(.*)\}' % number, text)[1]
    return body.split(r'\\')


def node(color, x, y, body, anchor='base', name=None):
    extra = (',name=%s' % name) if name else ''
    return r'\node[text=%s%s,anchor=%s,inner sep=0pt] at %s {%s};' % (
        color, extra, anchor, point(x, y), body)


def lettering(number, offsets):
    """Rules and type. Offsets are inches; positive moves that line's ink to the right."""
    number = str(number)
    off = offsets[number]
    title = json.loads((ROOT / 'common/series-catalog.json').read_text())['volumes'][number]['title']
    lines_title = title_lines(number, title)
    lines_sub = subtitle_lines(number)
    out = ['% lower-rule y=2.9500in; upper-rule y=6.9000in; shared by every volume.']
    out += rule(6.90) + rule(2.95)
    series = r'\resizebox{4.66in}{!}{\fS\fontsize{30}{34}\selectfont %s}' % trk('ORDER AND CHANCE', 13)
    out.append(node('ocCoverTitle', 3 + off['SERIES'], 7.56, series))
    out.append(node('ocCoverSub', 3 + off['SSUB'], 7.15,
                     r'\fR\fontsize{16.5}{19}\selectfont\itshape %s' % trk(r'\seriessubtitle', 2.5)))
    out.append(node('ocCoverNumber', 3 + off['VOL'], 2.66,
                     r'\fL\fontsize{9.5}{11}\selectfont %s' % trk('VOLUME %s' % number, 36), name='tVOL'))
    title_font = (r'\fontspec{CormorantGaramond-Regular.ttf}[Path=tools/assets/fonts/]'
                  r'\fontsize{42}{46}\selectfont ')
    for i, line in enumerate(lines_title):
        out.append(node('ocCoverTitle', 3 + off.get('T%d' % i, 0), 2.07 - 0.56 * i,
                         title_font + line, name='tT%d' % i))
    parts = []
    for i, line in enumerate(lines_sub):
        parts.append(r'\leavevmode\kern %.4fin %s' % (2 * off.get('S%d' % i, 0), line))
    body = r'\\'.join(parts)
    y = 1.785 - 0.56 * (len(lines_title) - 1)
    out.append(node(
        'ocCoverSub', 3.0, y,
        r'\fR\fontsize{19}{23.5}\selectfont\itshape\parbox[t]{5.2in}{\centering\hyphenpenalty=10000 '
        r'{\addfontfeatures{LetterSpace=2}%s}}' % body,
        anchor='north', name='tSUB'))
    out.append(node('ocCoverTitle', 3 + off['AUTHOR'], 0.56,
                     r'\fL\fontsize{10.5}{12}\selectfont %s' % trk('SEGHAIER Oussama', 22)))
    return out


def artwork(number):
    number = int(number)
    if number == 1:
        return collatz_art.art()
    scene, mode = arts.ARTS[number]()
    return scene.to_tikz(center=mode)


def plates(number, offsets):
    number = str(number)
    motif = '% Generated by tools/series_cover.py. Illustration only; the lockup is cover-lettering.tex.\n'
    motif += '\n'.join(artwork(number)) + '\n'
    lockup = '% Generated by tools/series_cover.py from baked optical shifts.\n'
    lockup += '\n'.join(lettering(number, offsets)) + '\n'
    return motif, lockup


def write_volume(number, offsets, root=ROOT):
    number = str(number)
    stem = json.loads((root / 'common/series-catalog.json').read_text())['volumes'][number]['stem']
    book = root / stem
    motif, lockup = plates(number, offsets)
    (book / 'cover-motif.tex').write_text(motif)
    (book / 'cover-lettering.tex').write_text(lockup)
    return book
