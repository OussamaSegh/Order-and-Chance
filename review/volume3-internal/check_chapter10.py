ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'volume3-symmetry/chapters/ch10-galois.tex'


def group_mul(g, h):
    a, b = g; c, d = h
    return ((a + (-1)**b*c) % 4, (b+d) % 2)


def closure(generators):
    group = {(0, 0)} | set(generators)
    while True:
        new = group | {group_mul(g, h) for g in group for h in group}
        if new == group:
            return frozenset(group)
        group = new


def action(g, v):
    a, b = g; out = [0]*8
    for j, c in enumerate(v):
        degree, imag = j % 4, j // 4
        k = imag + a*degree
        out[degree+4*(k % 2)] += c*(-1)**(b*imag+k//2)
    return out


def field_mul(v, w):
    out = [0]*8
    for i, a in enumerate(v):
        for j, b in enumerate(w):
            power, imag = i % 4+j % 4, i // 4+j // 4
            out[power % 4+4*(imag % 2)] += a*b*2**(power//4)*(-1)**(imag//2)
    return out


def rank(matrix):
    a = [[F(x) for x in row] for row in matrix]; r = 0
    for col in range(len(a[0]) if a else 0):
        pivot = next((j for j in range(r, len(a)) if a[j][col]), None)
        if pivot is None:
            continue
        a[r], a[pivot] = a[pivot], a[r]; u = a[r][col]
        a[r] = [x/u for x in a[r]]
        for j in range(len(a)):
            if j != r:
                u = a[j][col]; a[j] = [x-u*y for x, y in zip(a[j], a[r])]
        r += 1
        if r == len(a):
            break
    return r


def check_actual_lattice():
    elements = list(itertools.product(range(4), range(2)))
    subgroups = {closure(g for i, g in enumerate(elements) if mask >> i & 1)
                 for mask in range(256)}
    assert len(subgroups) == 10
    normal = {h for h in subgroups if all(
        {group_mul(g, x) for x in h} == {group_mul(x, g) for x in h}
        for g in elements)}
    assert len(normal) == 6
    labels = {
        'gt': closure([]), 'ga0': closure([(2, 1)]), 'ga1': closure([(0, 1)]),
        'ga2': closure([(2, 0)]), 'ga3': closure([(1, 1)]), 'ga4': closure([(3, 1)]),
        'gb0': closure([(2, 0), (0, 1)]), 'gb1': closure([(1, 0)]),
        'gb2': closure([(2, 0), (1, 1)]), 'gc': closure(elements)}
    assert set(labels.values()) == subgroups
    covers = {(a, b) for a, h in labels.items() for b, k in labels.items()
              if h < k and not any(h < m < k for m in subgroups)}
    source = (ROOT / 'volume3-symmetry/figures/ch10-lattice.tex').read_text()
    edges = set(re.findall(r'\((g\w+)\) -- \((g\w+)\)', source))
    field_edges = set(re.findall(r'\((f\w+)\) -- \((f\w+)\)', source))
    assert edges == covers and len(edges) == 15
    assert field_edges == {('f'+a[1:], 'f'+b[1:]) for a, b in covers}
    basis = [[int(i == j) for i in range(8)] for j in range(8)]
    plus = [a+b for a, b in zip(basis[1], basis[5])]
    minus = [a-b for a, b in zip(basis[1], basis[5])]
    generators = {'gt': [basis[1], basis[4]], 'ga0': [basis[5]],
                  'ga1': [basis[1]], 'ga2': [basis[2], basis[4]],
                  'ga3': [plus], 'ga4': [minus], 'gb0': [basis[2]],
                  'gb1': [basis[4]], 'gb2': [basis[6]], 'gc': [basis[0]]}
    for name, gens in generators.items():
        stabilizer = {g for g in elements if all(action(g, v) == v for v in gens)}
        assert stabilizer == labels[name]
        # Independently compute dimension of the field generated by these vectors.
        words = [basis[0]]
        while True:
            new = words + [field_mul(v, w) for v in words for w in gens]
            if rank(new) == rank(words):
                break
            words = new
        assert rank(words) == 8//len(stabilizer)
        # Solve the complete fixed-space equations, not only fixed generators.
        equations = []
        for g in stabilizer:
            cols = [[x-y for x, y in zip(action(g, v), v)] for v in basis]
            equations.extend(list(map(list, zip(*cols))))
        assert 8-rank(equations) == rank(words)
    for g, h in itertools.product(elements, repeat=2):
        for v in basis:
            assert action(group_mul(g, h), v) == action(g, action(h, v))


def check_periods_and_counts():
    a, b = {1, 2, 4}, {3, 5, 6}
    table = [[(x+y) % 7 for y in sorted(b)] for x in sorted(a)]
    assert table == [[4, 6, 0], [5, 0, 1], [0, 2, 3]]
    assert Counter(x for row in table for x in row) == Counter({0: 3, **{i: 1 for i in range(1, 7)}})
    powers = [pow(3, k, 17) for k in range(16)]
    assert len(set(powers)) == 16
    a, b = set(powers[::2]), set(powers[1::2])
    assert Counter((x+y) % 17 for x in a for y in b) == Counter({i: 4 for i in range(1, 17)})
    # F2^3: enumerate all subgroups, independently of the dual-space count.
    subs = {frozenset({0})}
    for mask in range(1 << 8):
        h = {i for i in range(8) if mask >> i & 1}
        if 0 in h and all(x ^ y in h for x in h for y in h):
            subs.add(frozenset(h))
    assert Counter(map(len, subs)) == {1: 1, 2: 7, 4: 7, 8: 1}
    assert [math.prod(p for j, p in enumerate((2, 3, 5)) if mask >> j & 1)
            for mask in range(1, 8)] == [2, 3, 6, 5, 10, 15, 30]
    def cycle_transposition_group(n, a, b):
        cycle = tuple((j+1) % n for j in range(n)); swap = list(range(n))
        swap[a], swap[b] = swap[b], swap[a]
        identity = tuple(range(n)); group = {identity}; queue = [identity]
        for g in queue:
            for h in (cycle, swap):
                gh = tuple(g[h[j]] for j in range(n))
                if gh not in group:
                    group.add(gh); queue.append(gh)
        return len(group)
    for p in (2, 3, 5):
        assert all(cycle_transposition_group(p, a, b) == math.factorial(p)
                   for a, b in itertools.combinations(range(p), 2))
    # Composite length: an unspecified long cycle and transposition need not suffice.
    assert cycle_transposition_group(6, 0, 3) == 24 < math.factorial(6)


def check_quintic_plot():
    def f(x):
        return x**5-4*x+2
    source = (ROOT / 'volume3-symmetry/figures/ch10-quintic-graph.tex').read_text()
    points = [tuple(map(F, p)) for p in re.findall(r'\(([-\d.]+),([-\d.]+)\)',
              re.search(r'coordinates \{(.*?)\}', source, re.S)[1])]
    assert len(points) == 3
    for (left, right), (x, y) in zip(((-2, 0), (0, 1), (1, 2)), points):
        a, b = F(left), F(right)
        while b-a > F(1, 10**14):
            m = (a+b)/2
            if f(a)*f(m) <= 0:
                b = m
            else:
                a = m
        assert abs(x-(a+b)/2) < F(5, 10**9) and y == 0
    assert [f(x) for x in (-2, 0, 1, 2)] == [-22, 2, -1, 26]
    assert F(5, 8)**4 != F(4, 5)  # General complex-common-root contradiction.
    assert 'samples=220' in source and '{x^5-4*x+2}' in source
    samples = [f(F(-172, 100)+F(327, 100)*j/219) for j in range(220)]
    assert sum(a*b < 0 for a, b in zip(samples, samples[1:])) == 3


def check_earned_order_and_local_cosine():
    source = SOURCE.read_text()
    end = source.index(r'\end{solution}', source.index(r'\begin{solution}{ex:phin}'))
    assert end < source.index(r'\label{thm:gw}')
    for kind in ('exercise', 'hint', 'solution'):
        marker = r'\label{ex:phin}' if kind == 'exercise' else r'\begin{'+kind+r'}{ex:phin}'
        assert source.index(marker) < end
    solution = re.search(r'\\begin\{solution\}\{pb:rattan\}(.*?)\\end\{solution\}', source, re.S)[1]
    assert 'ex:divides' not in solution and 'A sum of algebraic integers' not in solution
    # Exact integer recurrence: no future algebraic-integer closure theorem.
    polys = [[2], [0, 1]]
    for n in range(2, 30):
        xprevious = [0]+polys[-1]; old = polys[-2]+[0]*(len(xprevious)-len(polys[-2]))
        polys.append([a-b for a, b in zip(xprevious, old)])
    assert all(poly[-1] == 1 and len(poly) == n+1 for n, poly in enumerate(polys[1:], 1))
    assert polys[3] == [0, -3, 0, 1] and polys[4] == [2, 0, -4, 0, 1]


