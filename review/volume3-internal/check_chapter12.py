def check_actual_icosahedral_walk():
    from check_chapter11 import compose, inverse, cycle_counts
    group = [g for g in permutations(range(5))
             if sum(g[i] > g[j] for i in range(5) for j in range(i+1, 5)) % 2 == 0]
    identity = tuple(range(5)); cycle = (1, 2, 3, 4, 0)
    first_fives = {compose(compose(g, cycle), inverse(g)) for g in group}
    second_fives = {compose(compose(g, compose(cycle, cycle)), inverse(g)) for g in group}
    assert len(first_fives) == len(second_fives) == 12 and not first_fives & second_fives
    def column(g):
        if g == identity:
            return 0
        if cycle_counts(g)[2] == 2:
            return 1
        if cycle_counts(g)[3] == 1:
            return 2
        return 3 if g in first_fives else 4
    phi = Quad(Q(1, 2), Q(1, 2)); partner = 1-phi
    table = [(1, 1, 1, 1, 1), (3, -1, 0, phi, partner),
             (3, -1, 0, partner, phi), (4, 0, 1, -1, -1), (5, 1, -1, 0, 0)]
    eigenvalues = [Q(1), Q(0), Q(0), Q(1, 4), Q(-1, 5)]
    steps = [g for g in group if column(g) == 2]
    assert len(steps) == 20 and {inverse(g) for g in steps} == set(steps)
    counts = {identity: 1}
    for t in range(11):
        probabilities = {g: Q(counts.get(g, 0), 20**t) for g in group}
        assert sum(probabilities.values()) == 1
        assert probabilities[identity] == (1+18*Q(0)**t+16*Q(1, 4)**t+25*Q(-1, 5)**t)/60
        for g in group:
            predicted = sum(Quad.coerce(row[0]*row[column(g)])*eigenvalue**t/60
                            for row, eigenvalue in zip(table, eigenvalues))
            assert predicted == probabilities[g]
        fifth_turn = sum(probabilities[g] for g in first_fives)
        assert fifth_turn == (1+3*Q(0)**t-4*Q(1, 4)**t)/5
        if t == 0:
            assert probabilities[identity] == 1 and fifth_turn == 0
            assert Q(1+16+25, 60) == Q(7, 10) != probabilities[identity]
            assert Q(1-4, 5) == Q(-3, 5) != fifth_turn
        else:
            assert probabilities[identity] == (1+16*Q(1, 4)**t+25*Q(-1, 5)**t)/60
            assert fifth_turn == (1-4*Q(1, 4)**t)/5
            tv = sum(abs(p-Q(1, 60)) for p in probabilities.values())/2
            assert Q(4, 5)*Q(1, 4)**t <= tv <= Q(41, 2)*Q(1, 4)**t
        if t == 2:
            assert probabilities[identity] == Q(1, 20) and fifth_turn == Q(3, 20)
        new = Counter()
        for g, count in counts.items():
            for s in steps:
                new[compose(g, s)] += count
        counts = new


