#!/usr/bin/env python3
"""Regenerate volume15 figures/ch08-ratios.tex: M_k(T) over the conjectured leading term, k=1,2,3, T=10^3..10^6,
Monte Carlo on [T,2T] with the Riemann-Siegel formula (rs_zeta.py). Prints the ratios."""
import math, sys, numpy as np
from rs_zeta import Z
from common import primes_upto
def ak(k):
    s = 0.0
    for p in primes_upto(10 ** 6):
        u = 1 / p; s += k * k * math.log1p(-u) + math.log(sum(math.comb(k + r - 1, r) ** 2 * u ** r for r in range(60)))
    return math.exp(s)
G = lambda n: math.prod(math.factorial(j) for j in range(n - 1))
C = {k: ak(k) * G(k + 1) ** 2 / G(2 * k + 1) for k in (1, 2, 3)}
def ratios(T, n, seed):
    rng = np.random.default_rng(seed); t = rng.uniform(T, 2 * T, n); z = np.abs(Z(t)); L = np.log(t / (2 * math.pi))
    return {k: np.mean(z ** (2 * k)) / np.mean(C[k] * L ** (k * k)) for k in (1, 2, 3)}
if __name__ == "__main__":
    Ts = [10 ** 3, 10 ** 4, 10 ** 5, 10 ** 6]
    R = [ratios(T, 400000 if T < 10 ** 6 else 200000, 11 + i) for i, T in enumerate(Ts)]
    for T, r in zip(Ts, R): print(T, {k: round(v, 3) for k, v in r.items()})
    y = lambda v: 0.13 + 1.29 * math.log10(v)
    out = ["% moments / leading conjectured term (generated by review/volume15-rewrite/fig_ch10_ratios.py).",
           r"\begin{tikzpicture}[x=1cm,y=1cm]", r"\draw[black!35] (0,0) rectangle (7.00,4.00);"]
    for i, lab in enumerate(["10^3", "10^4", "10^5", "10^6"]):
        out.append(rf"\draw[black!35] ({7*i/3:.2f},0)--({7*i/3:.2f},-0.08) node[below,font=\tiny,black!60]{{${lab}$}};")
    for v, lab in [(1, "1"), (10, "10"), (100, "100"), (1000, "1000")]:
        out.append(rf"\draw[black!35] (0,{y(v):.2f})--(-0.08,{y(v):.2f}) node[left,font=\tiny,black!60]{{${lab}$}};")
    out.append(r"\node[below,font=\tiny,black!60] at (3.50,-0.35) {$T$};")
    out.append(r"\draw[black!50,dashed] (0,0.13)--(7.00,0.13);")
    for k, col in [(1, "black"), (2, "blue!70!black"), (3, "red!70!black")]:
        pts = [(7 * i / 3, y(r[k])) for i, r in enumerate(R)]
        out.append(rf"\draw[{col},thick] " + " -- ".join(f"({a:.3f},{b:.3f})" for a, b in pts) + ";")
        out += [rf"\fill[{col}] ({a:.3f},{b:.3f}) circle (0.05cm);" for a, b in pts]
    for k, col, yy in [(1, "black", 3.8), (2, "blue!70!black", 3.5), (3, "red!70!black", 3.2)]:
        out.append(rf"\draw[{col},thick] (5.60,{yy:.2f})--(6.00,{yy:.2f}) node[right,font=\tiny,black]{{$k={k}$}};")
    out.append(r"\end{tikzpicture}")
    open("../../volume15-order-and-chance/figures/ch08-ratios.tex", "w").write("\n".join(out) + "\n")
